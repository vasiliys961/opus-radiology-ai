#!/usr/bin/env python3
"""Install an opt-in unprivileged systemd USER service for ORIGINAL XRV worker.

Admin runs this once on the private Linux server, not when doctor loads DICOM.
It does not install dependencies, start anything, request OAuth, or read secrets
unless --enable-now is explicitly requested. No patient data is handled here.
"""
from __future__ import annotations
import argparse
import os
from pathlib import Path
import re
import subprocess
import sys

UNIT="opus-xrv-research.service"
_SAFE=re.compile(r"^/[a-zA-Z0-9_./-]+$")


def safe_path(path):
    p=Path(path).expanduser().resolve(strict=False)
    if not p.is_absolute() or not _SAFE.fullmatch(str(p)) or ".." in p.parts:
        raise ValueError("unsafe_systemd_path_use_simple_absolute_Linux_path")
    return p


def render_unit(repo, cache, python, next_env):
    repo=safe_path(repo);cache=safe_path(cache);python=safe_path(python)
    next_env=safe_path(next_env)
    script=repo/"scripts/start_xrv_research_worker.py"
    if not script.is_file() or script.is_symlink():
        raise ValueError("repository_original_XRV_bootstrap_not_present")
    if not python.is_file():
        raise ValueError("Python_interpreter_not_installed")
    if next_env.name!=".env.local" or next_env.parent!=repo/"web":
        raise ValueError("private_Next_server_environment_must_stay_in_repository_web")
    if cache==repo or cache==next_env or cache.is_relative_to(repo):
        raise ValueError("model_weights_cache_must_not_live_in_Git_repository")
    return f"""# Generated by scripts/install_xrv_user_service.py (research only)
# No tokens, OAuth credentials, paths to patient files or original images.
[Unit]
Description=Opus Radiology ORIGINAL NIH CXR TorchXRayVision research worker
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=180
StartLimitBurst=3

[Service]
Type=simple
WorkingDirectory={repo}
ExecStart={python} {script} --next-env {next_env} --cache {cache} --port 8779 --origin http://127.0.0.1:3000
Restart=on-failure
RestartSec=12
UMask=0077
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=full
ProtectHome=no
MemoryAccounting=yes
TasksMax=128
LimitNOFILE=4096
KillMode=control-group
TimeoutStopSec=15
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=default.target
"""


def install(unit_dir, content, *, replace=False):
    path=safe_path(unit_dir)
    path.mkdir(parents=True,exist_ok=True,mode=0o700)
    unit=path/UNIT
    if unit.is_symlink():
        raise ValueError("refuse_systemd_symlink_target")
    if unit.exists():
        if unit.read_text()==content:
            return unit,False
        if not replace:
            raise ValueError("existing_systemd_unit_requires_explicit_--replace")
    # Atomic replace in the same private directory; no token is printed.
    import tempfile
    with tempfile.NamedTemporaryFile("w",encoding="utf-8",dir=path,
       prefix=".opus-xrv-",delete=False) as out:
        pending=Path(out.name)
        out.write(content)
        out.flush()
        os.fsync(out.fileno())
    try:
        pending.chmod(0o600)
        if unit.is_symlink():
            raise ValueError("refuse_systemd_symlink_target")
        os.replace(pending,unit)
        unit.chmod(0o600)
    finally:
        pending.unlink(missing_ok=True)
    return unit,True


def enable_service(run=subprocess.run):
    # Nothing is enabled without an explicit operator --enable-now flag.
    run(["systemctl","--user","daemon-reload"],check=True)
    run(["systemctl","--user","enable","--now",UNIT],check=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    repo=Path(__file__).resolve().parents[1]
    parser.add_argument("--repo",type=Path,default=repo)
    parser.add_argument("--python",type=Path,default=Path(sys.executable))
    parser.add_argument("--cache",type=Path,
        default=Path.home()/".cache/opus-radiology/original-models/xrv")
    parser.add_argument("--unit-dir",type=Path,
        default=Path.home()/".config/systemd/user")
    parser.add_argument("--replace",action="store_true")
    parser.add_argument("--enable-now",action="store_true")
    args=parser.parse_args()
    if sys.platform!="linux":
        parser.error("Linux systemd user service only; Mac is an image browser")
    content=render_unit(args.repo,args.cache,args.python,
                        args.repo/"web/.env.local")
    path,changed=install(args.unit_dir,content,replace=args.replace)
    print("Unit:",path,"new_version:",changed)
    if args.enable_now:
        enable_service()
        print("Service enabled for this Linux user's systemd session.")
        print("The worker will be marked ready ONLY when original weights are verified.")
    else:
        print("Not started. Use --enable-now after installing original CPU dependencies.")
    print("No patient imaging data and no Yandex/OAuth secret were handled.")


if __name__=="__main__":
    main()
