export function hasRadiologistReportSections(value:unknown):value is string {
 if(typeof value!=="string"||value.length<120||value.length>4000)return false;
 const headings=["ИССЛЕДОВАНИЕ","ОПИСАНИЕ","ЗАКЛЮЧЕНИЕ","РЕКОМЕНДАЦИИ"];
 const positions=headings.map(h=>{
  const m=new RegExp("^"+h+"\\s*:", "mi").exec(value);
  return m?.index??-1;
 });
 if(positions.some(n=>n<0)||positions.some((n,i)=>i>0&&n<=positions[i-1]))return false;
 if(/(?:SOPInstanceUID|StudyInstanceUID|PatientName|sourceImageSha256|[a-f0-9]{64})/i.test(value))
  return false;
 return true;
}
